import numpy as np

# ============================================================
# 1. 改进 DH（MDH）参数表
# ============================================================
DH_PARAMS = [
    [0.0,    0.0,    0.0,  0.0],    # Joint 1：第 1 关节
    [10.25, -90.0,  21.0,  0.0],    # Joint 2：第 2 关节
    [104.0, -180.0, 21.0,  0.0],    # Joint 3：第 3 关节
    [0.0,   -90.0,  69.0,  0.0],    # Joint 4：第 4 关节
    [0.0,     0.0,  98.0,  0.0],    # Joint 5：第 5 关节，也是末端坐标系
]

# ============================================================
# 2. 计算单节改进 DH 齐次变换矩阵
# ============================================================
def mdh_transform(a, alpha_deg, d, theta_deg):
    """
    参数：
        a         ：MDH 参数 a，单位 mm
        alpha_deg ：MDH 参数 alpha，单位 degree
        d         ：MDH 参数 d，单位 mm
        theta_deg ：当前关节角度 theta，单位 degree
    返回：
        T_i：4×4 齐次变换矩阵
    """
    # 角度转换为弧度
    alpha = np.deg2rad(alpha_deg)
    theta = np.deg2rad(theta_deg)

    # 提前计算三角函数，避免在矩阵中重复调用。
    ca = np.cos(alpha)
    sa = np.sin(alpha)

    ct = np.cos(theta)
    st = np.sin(theta)

    # 计算齐次变换矩阵
    return np.array([
        [ct,      -st,       0.0,       a],
        [st * ca, ct * ca,  -sa, -d * sa],
        [st * sa, ct * sa,   ca,  d * ca],
        [0.0,      0.0,      0.0,     1.0]
    ], dtype=float)

# ============================================================
# 3. 计算基坐标系到末端坐标系的齐次变换矩阵
# ============================================================
def forward_kinematics(theta):
    """
    返回：
        T05：4×4 齐次变换矩阵，描述基坐标系到末端坐标系的变换。
        R05：3×3 旋转矩阵，描述末端相对于基座的姿态。
        p05：3×1 平移向量，表示末端原点在基坐标系中的位置。单位为 mm。
    """
    # 将输入角度转换为 NumPy 数组，方便后续计算。
    theta = np.asarray(theta, dtype=float).reshape(-1)

    # 检查关节角度数量是否正确。
    if theta.size != 5:
        raise ValueError("必须输入五个关节角度")

    # 检查角度是否包含 NaN 或无穷大等无效数值。
    if not np.all(np.isfinite(theta)):
        raise ValueError("关节角度必须是有限数值")

    # T = np.zeros((4, 4)) 创建一个全部为 0 的 \(4\times4\) 矩阵
    # 创建 4×4 单位矩阵
    T05 = np.eye(4)

    # 依次计算每个关节的单节变换矩阵，并进行连乘。
    # angle：当前关节的实际角度。
    # a、alpha、d、offset：当前关节对应的 MDH 参数。
    for angle, (a, alpha, d, _) in zip(theta, DH_PARAMS):

        # 当前关节的实际计算角度。
        # 如果关节存在零位偏置，需要将偏置加到实际角度上。
        theta_i = angle

        # 计算当前关节对应的单节齐次变换矩阵。
        Ti = mdh_transform(a, alpha, d, theta_i)

        # 将当前单节变换矩阵乘到累计矩阵上。
        # 连乘关系：
        # T05 = T01 @ T12 @ T23 @ T34 @ T45
        T05 = T05 @ Ti

    # 提取齐次变换矩阵左上角的 3×3 旋转矩阵。
    R05 = T05[:3, :3]

    # 提取齐次变换矩阵右上角的 3×1 平移向量。
    p05 = T05[:3, 3].reshape(3, 1)

    # 返回完整位姿，以及拆分后的旋转和平移数据。
    return T05, R05, p05

# ============================================================
# 4. 主程序：测试正运动学计算
# ============================================================
if __name__ == "__main__":

    # 输入一组测试关节角度。
    # 实际进行手眼标定时，替换为每张图片对应的真实关节角度。
    theta = [0, 30, 45, 20, 0]

    # 根据当前关节角度计算机械臂末端位姿。
    T05, R05, p05 = forward_kinematics(theta)

    # 设置 NumPy 的输出格式：
    # 保留 4 位小数，并省略不必要的科学计数法。
    np.set_printoptions(precision=4, suppress=True)

    # 输出完整齐次变换矩阵。
    print("基坐标系到末端坐标系的齐次变换矩阵 T05：")
    print(T05)

    # 输出末端旋转矩阵。
    print("\n末端旋转矩阵 R05：")
    print(R05)

    # 输出末端在基坐标系中的位置。
    print("\n末端位置 p05 (mm)：")
    # 将多维数组展开成一维数组
    print(p05.ravel())